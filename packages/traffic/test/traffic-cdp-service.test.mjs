import test from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { WebSocketServer } from 'ws';
import { createCdpService } from 'codex-toolkit-core/cdp';
import { createTrafficService } from '../src/traffic-service.mjs';
import { createTrafficObserverRouter } from '../src/traffic-observer-router.mjs';

test('optional CDP shares one browser connection, keeps the SQLite owner and releases only its own trace', async t => {
  let starts = 0, ends = 0, connections = 0;
  let service, router;
  const server = http.createServer((request, response) => {
    response.setHeader('content-type', 'application/json');
    response.end(JSON.stringify({ webSocketDebuggerUrl: `ws://127.0.0.1:${server.address().port}/devtools/browser/fixture` }));
  });
  const sockets = new WebSocketServer({ server });
  sockets.on('connection', socket => { connections++; socket.on('message', bytes => {
    const message = JSON.parse(bytes);
    if (message.method === 'Tracing.start') starts++;
    if (message.method === 'Tracing.end') ends++;
    socket.send(JSON.stringify({ id: message.id, result: message.method === 'Target.getTargets' ? { targetInfos: [] } : {} }));
    if (message.method === 'Tracing.end') socket.send(JSON.stringify({ method: 'Tracing.tracingComplete', params: {} }));
  }); });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const cdp = await createCdpService([server.address().port]);
  const other = await cdp.forOwner('themes').acquire();
  t.after(async () => { await router?.close(); await service?.close(); await other.close(); await cdp.close(); for (const socket of sockets.clients) socket.terminate(); await new Promise(resolve => sockets.close(resolve)); await new Promise(resolve => server.close(resolve)); });
  const stateDirectory = await fs.mkdtemp(path.join(os.tmpdir(), 'bandwidth-cdp-'));
  const errors = [], snapshots = []; let recovered;
  service = await createTrafficService({ stateDirectory, cdp: cdp.forOwner('bandwidth'), cdpPort: cdp.port, changed: value => { errors.push(...value); snapshots.push(value); if (!value.length) recovered?.(); }, diagnostic: () => {} });
  await service.setCapture(true);
  assert.equal(starts, 1);
  const resumed = new Promise(resolve => { recovered = resolve; });
  other.socket.close();
  await resumed;
  assert.equal(connections, 2); assert.equal(starts, 2);
  assert.deepEqual(snapshots.at(-1), []);
  assert.notEqual(service.query().coverage.find(item => item.id === 'cdp-protocol').status, 'error');
  assert.equal(service.query().coverage.find(item => item.id === 'chromium').status, 'active');
  assert.equal(connections, 2);
  await service.setCapture(true);
  assert.equal(starts, 2);
  await service.setCapture(false);
  assert.equal(ends, 1);
  assert.equal(service.query().coverage.find(item => item.id === 'chromium').status, 'paused');
  assert.ok(errors.length > 0, 'the disconnection remains in diagnostics');
  const pausedResume = new Promise(resolve => { recovered = resolve; });
  const current = await cdp.forOwner('themes').acquire();
  current.socket.close(); await pausedResume;
  assert.equal(starts, 2, 'reconnect must not override an explicit pause');
  assert.equal(service.query().coverage.find(item => item.id === 'chromium').status, 'paused');
  await (await cdp.forOwner('themes').acquire()).send('Runtime.fixture');
  assert.equal(connections, 3);
  const capture = service.captureState(); assert.deepEqual(capture, { requested: true, paused: true });
  const artifactRoot = await fs.mkdtemp(path.join(os.tmpdir(), 'cdtk-traffic-cdp-kit-')); t.after(() => fs.rm(artifactRoot, { recursive: true }));
  const packer = path.join(path.dirname(fileURLToPath(import.meta.resolve('codex-toolkit-core/kits'))), 'feature-pack.mjs');
  const entry = fileURLToPath(new URL('../kits/traffic-observer/index.mjs', import.meta.url));
  const { stdout } = await promisify(execFile)(process.execPath, [packer, entry, artifactRoot], { windowsHide: true, encoding: 'utf8' });
  const packaged = await import(pathToFileURL(path.join(JSON.parse(stdout).output, 'backend.mjs')).href);
  await service.close(); service = await packaged.createTrafficService({ stateDirectory, cdp: cdp.forOwner('bandwidth'), cdpPort: cdp.port, initialCapture: capture, changed: value => snapshots.push(value), diagnostic: () => {} });
  for (let i = 0; i < 200 && service.query().coverage.find(item => item.id === 'chromium').status !== 'paused'; i++) await new Promise(resolve => setTimeout(resolve, 5));
  assert.equal(service.query().coverage.find(item => item.id === 'chromium').status, 'paused'); assert.equal(starts, 2); assert.equal(connections, 3);
  await service.setCapture(true); assert.equal(starts, 3);
  const activeService = service; router = await createTrafficObserverRouter(async () => activeService, { stateDirectory, cdp: cdp.forOwner('bandwidth'), cdpPort: cdp.port, changed: () => {}, diagnostic: () => {} }); service = null;
  await router.replace(packaged.createTrafficService);
  for (let i = 0; i < 200 && (await router.query({})).coverage.find(item => item.id === 'chromium').status !== 'active'; i++) await new Promise(resolve => setTimeout(resolve, 5));
  const coverage = (await router.query({})).coverage; assert.equal(coverage.find(item => item.id === 'chromium').status, 'active'); assert.equal(coverage.find(item => item.id === 'observer-handoff').status, 'gap');
  assert.equal(starts, 4); assert.equal(ends, 2); assert.equal(connections, 3);
});
